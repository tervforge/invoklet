namespace Invoklet.Avalonia.Themes;

public enum ThemeKeyType
{
    Color,
    Double,
    Thickness,
    CornerRadius,
    Geometry,
}

/// <summary>A resource that an interface theme can supply. An alias resolves to the named canonical key.</summary>
public sealed record ThemeKey(string Name, ThemeKeyType Type, string Description, string? AliasFor = null, bool IsRawColor = false);

