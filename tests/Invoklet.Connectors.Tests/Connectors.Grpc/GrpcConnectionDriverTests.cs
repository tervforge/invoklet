using Invoklet.Connectors.Grpc;
using Invoklet.Connectors.Tests.Connectors.Grpc.Fixtures;
using Invoklet.Contracts.Connections;
using Invoklet.Format.MdRun;
using Xunit;

namespace Invoklet.Connectors.Tests.Connectors.Grpc;

// What the gRPC driver checks in a connection and the client code it writes for the script. Reaching a real server is the integration tests' part.
[Trait("Platform", "Independent")]
public sealed class GrpcConnectionDriverTests
{
    [Theory]
    [InlineData("https://${env:INVENTORY_HOST}")]
    [InlineData("http://localhost:5001")]
    [InlineData("localhost:5001")]
    public void Validate_AnAddress_ReportsNothing(string address)
    {
        // Arrange
        var sut = new GrpcConnectionDriverFixture().CreateSut();

        // Act
        var problems = sut.Validate(GrpcConnectionDriverFixture.Connection(address));

        // Assert
        Assert.Empty(problems);
    }

    [Fact]
    public void Validate_NoAddress_SaysTheAddressIsMissing()
    {
        // Arrange
        var sut = new GrpcConnectionDriverFixture().CreateSut();

        // Act
        var problems = sut.Validate(new MdRunConnection { Name = "inventory", Driver = GrpcConnectionDriver.DriverId });

        // Assert
        Assert.Equal(["The address is missing."], problems);
    }

    [Fact]
    public void Validate_AnAddressOfAnotherProtocol_SaysItIsNoHostAndPort()
    {
        // Arrange
        var sut = new GrpcConnectionDriverFixture().CreateSut();

        // Act
        var problems = sut.Validate(GrpcConnectionDriverFixture.Connection("ftp://localhost:5001"));

        // Assert
        Assert.Equal(["The address 'ftp://localhost:5001' is not a host and port, or an http:// or https:// address."], problems);
    }

    [Fact]
    public void Validate_ABinaryMetadataName_SaysItCantBeOne()
    {
        // Arrange
        var sut = new GrpcConnectionDriverFixture().CreateSut();

        // Act
        var problems = sut.Validate(GrpcConnectionDriverFixture.WithMetadataName("token-bin"));

        // Assert
        Assert.Equal(["'token-bin' can't be a metadata name: use letters, digits, '-', '_' and '.', and no '-bin' ending."], problems);
    }

    [Fact]
    public void Validate_ASkipCertificateCheckThatIsNoBoolean_SaysItMustBeTrueOrFalse()
    {
        // Arrange
        var sut = new GrpcConnectionDriverFixture().CreateSut();

        // Act
        var problems = sut.Validate(GrpcConnectionDriverFixture.Connection(skipCertificateCheck: "yes"));

        // Assert
        Assert.Equal(["Skip the certificate check must be true or false, not 'yes'."], problems);
    }

    // The Test button gets the parameters unchecked: a name Metadata refuses is a message, before any connection is made.
    [Theory]
    [InlineData("bad key")]
    [InlineData("token-bin")]
    public async Task TestAsync_AnInvalidMetadataName_SaysWhyWithoutConnecting(string name)
    {
        // Arrange
        var sut = new GrpcConnectionDriverFixture().CreateSut();

        // Act
        var result = await sut.TestAsync(GrpcConnectionDriverFixture.TestParams(name), TestContext.Current.CancellationToken);

        // Assert
        Assert.Equal(new ConnectionTestResult(false,
            $"'{name}' can't be a metadata name: use letters, digits, '-', '_' and '.', and no '-bin' ending."), result);
    }

    // protoc's files are <auto-generated>, where nullable is off: the directive goes after the header comment, whatever the line endings.
    [Theory]
    [InlineData("// <auto-generated>\n//   x\n// </auto-generated>\n#pragma warning disable 1591\nclass A { }\n",
        "// <auto-generated>\n//   x\n// </auto-generated>\n#nullable enable annotations\n#pragma warning disable 1591\nclass A { }\n")]
    [InlineData("// <auto-generated>\r\n// </auto-generated>\r\nclass A { }",
        "// <auto-generated>\r\n// </auto-generated>\r\n#nullable enable annotations\r\nclass A { }")]
    [InlineData("class A { }", "#nullable enable annotations\nclass A { }")]
    [InlineData("", "#nullable enable annotations\n")]
    public void WithNullableContext_AGeneratedFile_GetsTheDirectiveAfterItsHeader(string source, string expected)
    {
        // Act
        var withDirective = GrpcConnectionDriver.WithNullableContext(source);

        // Assert
        Assert.Equal(expected, withDirective);
    }

    [Fact]
    public void CreateClient_TheServicesOfTheSchema_GetAPropertyEach()
    {
        // Arrange
        var fixture = new GrpcConnectionDriverFixture();
        fixture.ServerHas(("inventory.v1.Stock", "global::Inventory.V1.Stock.StockClient", "Stock"));
        var sut = fixture.CreateSut();

        // Act
        var generated = GeneratedConnections.For([GrpcConnectionDriverFixture.Connection()], MdRunLanguage.CSharp, fixture.Packages(sut),
            fixture.Drivers(sut), fixture.Schemas.Object)!;

        // Assert
        Assert.Empty(generated.Errors);
        Assert.Contains("public global::Inventory.V1.Stock.StockClient Stock => __stock ??= new global::Inventory.V1.Stock.StockClient(CallInvoker);",
            generated.Source, StringComparison.Ordinal);
    }

    // The connection's metadata goes in a Metadata of its own for each call, so the one a script passes and reuses is left as it was.
    [Fact]
    public void CreateClient_MetadataOfTheConnection_IsSentWithoutAddingToTheCallersOwn()
    {
        // Arrange
        var fixture = new GrpcConnectionDriverFixture();
        fixture.ServerHas();
        var sut = fixture.CreateSut();

        // Act
        var generated = GeneratedConnections.For([GrpcConnectionDriverFixture.Connection(authorization: "Bearer ${secret:token}")],
            MdRunLanguage.CSharp, fixture.Packages(sut), fixture.Drivers(sut), fixture.Schemas.Object)!;

        // Assert
        Assert.Contains("var all = new global::Grpc.Core.Metadata();", generated.Source, StringComparison.Ordinal);
        Assert.Contains("if (headers is not null) foreach (var entry in headers) all.Add(entry);", generated.Source, StringComparison.Ordinal);
        Assert.DoesNotContain("headers.Add(", generated.Source, StringComparison.Ordinal);
    }

    // Plaintext HTTP/2 on any port (the Postman Echo server is http:// on 443), and the certificate check left alone.
    [Fact]
    public void CreateClient_AnHttpAddress_IsUsedAsWritten_WithTheCertificateCheckKept()
    {
        // Arrange
        var fixture = new GrpcConnectionDriverFixture();
        fixture.ServerHas();
        var sut = fixture.CreateSut();

        // Act
        var generated = GeneratedConnections.For([GrpcConnectionDriverFixture.Connection("http://grpc.postman-echo.com:443")],
            MdRunLanguage.CSharp, fixture.Packages(sut), fixture.Drivers(sut), fixture.Schemas.Object)!;

        // Assert
        Assert.Contains("GrpcChannel.ForAddress(\"http://grpc.postman-echo.com:443\", new global::Grpc.Net.Client.GrpcChannelOptions { HttpHandler = handler });",
            generated.Source, StringComparison.Ordinal);
        Assert.DoesNotContain("RemoteCertificateValidationCallback", generated.Source, StringComparison.Ordinal);
    }

    [Fact]
    public void CreateClient_SkipCertificateCheck_AcceptsAnyCertificate()
    {
        // Arrange
        var fixture = new GrpcConnectionDriverFixture();
        fixture.ServerHas();
        var sut = fixture.CreateSut();

        // Act
        var generated = GeneratedConnections.For([GrpcConnectionDriverFixture.Connection(skipCertificateCheck: "true")],
            MdRunLanguage.CSharp, fixture.Packages(sut), fixture.Drivers(sut), fixture.Schemas.Object)!;

        // Assert
        Assert.Contains("RemoteCertificateValidationCallback = (_, _, _, _) => true;", generated.Source, StringComparison.Ordinal);
    }

    // A service property named like the connection's own client class would hide it: it gets the service's package in its name.
    [Fact]
    public void CreateClient_AServicePropertyNamedLikeTheClientClass_IsRenamed()
    {
        // Arrange
        var fixture = new GrpcConnectionDriverFixture();
        fixture.ServerHas(("example.InventoryClient", "global::Example.Client", "InventoryClient"));
        var sut = fixture.CreateSut();

        // Act
        var generated = GeneratedConnections.For([GrpcConnectionDriverFixture.Connection()], MdRunLanguage.CSharp, fixture.Packages(sut),
            fixture.Drivers(sut), fixture.Schemas.Object)!;

        // Assert
        Assert.Contains("public global::Example.Client ExampleInventoryClient =>", generated.Source, StringComparison.Ordinal);
        Assert.DoesNotContain("public global::Example.Client InventoryClient =>", generated.Source, StringComparison.Ordinal);
    }
}
