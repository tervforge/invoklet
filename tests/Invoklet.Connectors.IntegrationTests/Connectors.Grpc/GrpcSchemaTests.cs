using Google.Protobuf.Reflection;
using Invoklet.Connectors.Grpc;
using Invoklet.Connectors.IntegrationTests.Connectors.Grpc.Fixtures;
using Invoklet.Contracts.Connections;
using Invoklet.Format.MdRun;
using Invoklet.Languages.DotnetCommon;
using Invoklet.Windows.Models;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Xunit;

namespace Invoklet.Connectors.IntegrationTests.Connectors.Grpc;

// What a gRPC connection reads from a real server (through server reflection) and has protoc write, and how a failed read is reported.
public sealed class GrpcSchemaTests(GrpcServersFixture servers) : IClassFixture<GrpcServersFixture>, IDisposable
{
    private readonly string _folder = Directory.CreateTempSubdirectory("Invoklet-grpc-schema").FullName;

    public void Dispose() => Directory.Delete(_folder, true);

    private ConnectionSchemas Schemas()
    {
        var drivers = new ConnectionDriverRegistry();
        drivers.Register(new GrpcConnectionDriver());
        return new ConnectionSchemas(drivers, Path.Combine(_folder, "schemas"), DotnetConnectionTools.Default,
            name => name == "inventory-token" ? "t0k" : null);
    }

    private static FileDescriptorProto Proto(string version)
    {
        var file = new FileDescriptorProto { Name = $"x/{version}/service.proto", Package = $"x.{version}", Syntax = "proto3" };
        file.MessageType.Add(new DescriptorProto { Name = "Ping" });
        var service = new ServiceDescriptorProto { Name = "Echo" };
        service.Method.Add(new MethodDescriptorProto { Name = "Send", InputType = $".x.{version}.Ping", OutputType = $".x.{version}.Ping" });
        file.Service.Add(service);
        return file;
    }

    private static async Task<IReadOnlyList<GeneratedSourceFile>> ProtocOfTwoPackagesAsync()
    {
        var tools = await DotnetConnectionTools.Default.GetPackageFolderAsync("Grpc.Tools", GrpcConnectionDriver.GrpcVersion,
            TestContext.Current.CancellationToken);
        return await GrpcConnectionDriver.ProtocAsync(tools, [Proto("v1"), Proto("v2")], TestContext.Current.CancellationToken);
    }

    // x/v1/service.proto and x/v2/service.proto are written to folders of their own instead of over each other.
    [Fact]
    public async Task ProtocAsync_FilesOfOneNameInTwoPackages_AreWrittenToFoldersOfTheirOwn()
    {
        // Act
        var files = await ProtocOfTwoPackagesAsync();

        // Assert
        Assert.Equal(["X/V1/Service.cs", "X/V1/ServiceGrpc.cs", "X/V2/Service.cs", "X/V2/ServiceGrpc.cs"], files.Select(f => f.Name));
    }

    [Fact]
    public async Task ProtocAsync_TheWrittenFiles_EnableNullableAnnotations()
    {
        // Act
        var files = await ProtocOfTwoPackagesAsync();

        // Assert
        Assert.All(files, f => Assert.Contains("#nullable enable annotations", f.Text, StringComparison.Ordinal));
    }

    [Fact]
    public async Task ProtocAsync_TwoPackagesWithOneServiceName_GiveAClientAndAPropertyEach()
    {
        // Arrange
        var files = await ProtocOfTwoPackagesAsync();

        // Act
        var clients = GrpcClientParser.WithProperties(GrpcClientParser.Find(files, ["x.v1.Echo", "x.v2.Echo"]));

        // Assert
        Assert.Equal(["global::X.V1.Echo.EchoClient", "global::X.V2.Echo.EchoClient"], clients.Select(c => c.ClientType));
        Assert.Equal(["XV1Echo", "XV2Echo"], clients.Select(c => c.Property));
    }

    // The directive only enables annotations: a file that writes T? compiles without CS8669 and without nullable warnings of its own.
    [Fact]
    public void WithNullableContext_GeneratedCodeWithAnnotations_CompilesWithoutNullableWarnings()
    {
        // Arrange
        const string generated = "// <auto-generated>\nclass A\n{\n    public string? Value { get; set; }\n    public string Text => Value;\n}\n";

        // Act
        var tree = CSharpSyntaxTree.ParseText(GrpcConnectionDriver.WithNullableContext(generated), cancellationToken: TestContext.Current.CancellationToken);
        var diagnostics = CSharpCompilation.Create("Generated", [tree], [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary)).GetDiagnostics(TestContext.Current.CancellationToken);

        // Assert
        Assert.DoesNotContain(diagnostics, d => d.Id.StartsWith("CS86", StringComparison.Ordinal));
    }

    [Fact]
    public async Task EnsureAsync_AServerWithReflection_SummarisesItsServices()
    {
        // Arrange
        var schemas = Schemas();
        var connection = servers.Inventory();

        // Act
        await schemas.EnsureAsync([connection], null, ConnectionSchemaRefresh.Failed, TestContext.Current.CancellationToken);

        // Assert
        Assert.Null(schemas.Cache.ErrorFor(connection));
        Assert.Equal("2 services: inventory.v1.Audit, inventory.v1.Stock.", schemas.Cache.Get(connection)!.Summary);
    }

    // The services' classes, without what Google.Protobuf already has (Timestamp), each enabling nullable annotations.
    [Fact]
    public async Task EnsureAsync_AServerWithReflection_WritesTheClassesOfItsServices()
    {
        // Arrange
        var schemas = Schemas();
        var connection = servers.Inventory();

        // Act
        await schemas.EnsureAsync([connection], null, ConnectionSchemaRefresh.Failed, TestContext.Current.CancellationToken);

        // Assert
        var files = schemas.Cache.Get(connection)!.Files;
        Assert.Contains(files, f => f.Name == "Inventory/V1/Inventory.cs");
        Assert.Contains(files, f => f.Name == "Inventory/V1/InventoryGrpc.cs");
        Assert.DoesNotContain(files, f => f.Name.Contains("Timestamp", StringComparison.Ordinal));
        Assert.All(files, f => Assert.Contains("#nullable enable annotations", f.Text, StringComparison.Ordinal));
    }

    // The shapes the Connections window finds a service's client, its methods and a message by.
    [Fact]
    public async Task EnsureAsync_TheWrittenClasses_HaveTheShapesTheConnectionsWindowFindsThemBy()
    {
        // Arrange
        var schemas = Schemas();
        var connection = servers.Inventory();

        // Act
        await schemas.EnsureAsync([connection], null, ConnectionSchemaRefresh.Failed, TestContext.Current.CancellationToken);

        // Assert
        var files = schemas.Cache.Get(connection)!.Files;
        var grpc = files.Single(f => f.Name == "Inventory/V1/InventoryGrpc.cs").Text;
        Assert.Matches(@"\bnamespace Inventory\.V1\s*[{;]", grpc);
        Assert.Matches(@"\bclass Stock\b[\s\S]*\bclass StockClient\b[\s\S]*\bGetItem\(", grpc);
        Assert.Contains(files, f => f.Text.Contains("class ItemRequest : pb::IMessage<ItemRequest>", StringComparison.Ordinal));
    }

    [Fact]
    public async Task EnsureAsync_ASchemaAlreadyRead_IsNotReadAgain()
    {
        // Arrange
        var schemas = Schemas();
        var connection = servers.Inventory();
        await schemas.EnsureAsync([connection], null, ConnectionSchemaRefresh.Failed, TestContext.Current.CancellationToken);

        // Act
        var readAgain = await schemas.EnsureAsync([connection], null, ConnectionSchemaRefresh.Failed, TestContext.Current.CancellationToken);

        // Assert
        Assert.False(readAgain);
    }

    // A server that can't be read is a build error with the reason.
    [Fact]
    public async Task EnsureAsync_AServerWithoutReflection_MakesTheReasonABuildError()
    {
        // Arrange
        var schemas = Schemas();
        var connection = servers.Inventory(servers.PlainAddress, metadata: null);

        // Act
        await schemas.EnsureAsync([connection], null, ConnectionSchemaRefresh.Missing, TestContext.Current.CancellationToken);

        // Assert
        Assert.Equal(
            ["Connection 'inventory': its description couldn't be read: The server doesn't offer gRPC server reflection, which Invoklet reads its services with."],
            GeneratedConnections.For([connection], MdRunLanguage.CSharp, new GrpcConnectionDriver().Packages.Keys, schemas.Drivers, schemas.Cache)!.Errors);
    }

    // The editor reads in the background only what was never read: a failed server isn't asked again on every edit.
    [Fact]
    public async Task EnsureAsync_MissingAfterAFailedRead_DoesNotAskAgain()
    {
        // Arrange
        var schemas = Schemas();
        var connection = servers.Inventory(servers.PlainAddress, metadata: null);
        await schemas.EnsureAsync([connection], null, ConnectionSchemaRefresh.Missing, TestContext.Current.CancellationToken);

        // Act
        var asked = await schemas.EnsureAsync([connection], null, ConnectionSchemaRefresh.Missing, TestContext.Current.CancellationToken);

        // Assert
        Assert.False(asked);
    }

    // A run asks a failed server again.
    [Fact]
    public async Task EnsureAsync_FailedAfterAFailedRead_AsksAgain()
    {
        // Arrange
        var schemas = Schemas();
        var connection = servers.Inventory(servers.PlainAddress, metadata: null);
        await schemas.EnsureAsync([connection], null, ConnectionSchemaRefresh.Missing, TestContext.Current.CancellationToken);

        // Act
        var asked = await schemas.EnsureAsync([connection], null, ConnectionSchemaRefresh.Failed, TestContext.Current.CancellationToken);

        // Assert
        Assert.True(asked);
    }

    [Fact]
    public async Task EnsureAsync_AMissingSecret_IsTheReason()
    {
        // Arrange
        var schemas = Schemas();
        var connection = servers.Inventory(metadata: "Bearer ${secret:nope}");

        // Act
        await schemas.EnsureAsync([connection], null, ConnectionSchemaRefresh.Failed, TestContext.Current.CancellationToken);

        // Assert
        Assert.Equal("The Secret Store has no secret named 'nope'. Add it in Tools → Secret Store.", schemas.Cache.ErrorFor(connection));
    }

    // Dependencies → Connections says why too.
    [Fact]
    public async Task ScriptConnections_AServerThatCanNotBeRead_ShowsTheReason()
    {
        // Arrange
        var schemas = Schemas();
        var connection = servers.Inventory(servers.PlainAddress, metadata: null);
        await schemas.EnsureAsync([connection], null, ConnectionSchemaRefresh.Missing, TestContext.Current.CancellationToken);
        var packages = new GrpcConnectionDriver().Packages.Keys;
        var tab = new ScriptConnectionsViewModel(null, null, schemas.Drivers, schemas);
        tab.UsePackages(() => new HashSet<string>(packages, StringComparer.OrdinalIgnoreCase), (_, _) => { });

        // Act
        tab.Load(new MdRunFrontMatter { Connections = [connection] });

        // Assert
        Assert.Equal("Its description couldn't be read: The server doesn't offer gRPC server reflection, which Invoklet reads its services with.",
            Assert.Single(tab.Items).Problem);
    }
}
